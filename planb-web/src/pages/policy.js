import { View } from '../core/view.js';
import { html, when } from '../core/dom.js';

class PolicyView extends View {
  get content() {
    return { title: '', updated: '', intro: '', sections: [], notice: '' };
  }

  template() {
    const { title, updated, intro, sections, notice } = this.content;
    return html`
      <div class="page-scroll">
        <article class="policy-page">
          <div class="title">${title}</div>
          <div class="updated">${updated}</div>
          ${when(intro, html`<div class="intro">${intro}</div>`)}
          ${sections.map(([heading, text]) => html`
            <div class="section">
              <div class="heading">${heading}</div>
              <div class="text">${text}</div>
            </div>
          `)}
          ${when(notice, html`<div class="notice">${notice}</div>`)}
        </article>
      </div>
    `;
  }
}

